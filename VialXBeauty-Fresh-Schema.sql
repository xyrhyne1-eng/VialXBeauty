create table if not exists public.payment_methods (
  id bigint generated by default as identity primary key,
  payment_name text not null,
  short_description text,
  instructions text,
  instructions_visible boolean not null default true,
  cod_fee numeric(12,2) not null default 0,
  receipt_required boolean not null default false,
  reference_required boolean not null default false,
  deposit_required boolean not null default false,
  deposit_percentage numeric(5,2) not null default 0,
  qr_url text,
  is_visible boolean not null default true,
