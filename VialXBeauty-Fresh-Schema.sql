  ('product-images','product-images',true),
  ('payment-qr','payment-qr',true),
  ('payment-receipts','payment-receipts',false)
on conflict (id) do update set public = excluded.public;

do $$ begin
  execute 'drop policy if exists product_images_public_read on storage.objects';
  execute 'drop policy if exists product_images_admin_write on storage.objects';
  execute 'drop policy if exists payment_qr_public_read on storage.objects';
  execute 'drop policy if exists payment_qr_admin_write on storage.objects';
  execute 'drop policy if exists payment_receipts_admin_read on storage.objects';
  execute 'drop policy if exists payment_receipts_anon_insert on storage.objects';
  execute 'drop policy if exists payment_receipts_admin_delete on storage.objects';
end $$;

create policy product_images_public_read on storage.objects for select using (bucket_id = 'product-images');
create policy product_images_admin_write on storage.objects for all to authenticated using (bucket_id = 'product-images' and public.is_admin()) with check (bucket_id = 'product-images' and public.is_admin());
create policy payment_qr_public_read on storage.objects for select using (bucket_id = 'payment-qr');
create policy payment_qr_admin_write on storage.objects for all to authenticated using (bucket_id = 'payment-qr' and public.is_admin()) with check (bucket_id = 'payment-qr' and public.is_admin());
