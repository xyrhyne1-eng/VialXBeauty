-- Storefront order placement. This function is intentionally the public write path for orders.
create or replace function public.place_storefront_order(p_order jsonb, p_items jsonb)
returns table(order_id text, order_ref text)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order_id uuid;
  v_order_ref text;
  v_item_json jsonb;
begin
  if coalesce(trim(p_order->>'order_ref'), '') = '' then raise exception 'Order reference is required'; end if;
  if jsonb_typeof(p_items) is distinct from 'array' or jsonb_array_length(p_items) = 0 then raise exception 'At least one order item is required'; end if;

  insert into public.orders (
    order_ref, customer_name, customer_username, phone, email, address,
    province, city, barangay, street, house_unit, zipcode, payment_method,
    shipping_method, shipping_method_type, notes, shipping_fee, payment_fee,
    subtotal, total, amount_paid, payment_status, receipt_image,
    reference_number, paid_at, status
  ) values (
    trim(p_order->>'order_ref'), trim(p_order->>'customer_name'),
    nullif(trim(p_order->>'customer_username'), ''), trim(p_order->>'phone'),
    nullif(trim(p_order->>'email'), ''), trim(p_order->>'address'),
    trim(p_order->>'province'), trim(p_order->>'city'), trim(p_order->>'barangay'),
    trim(p_order->>'street'), trim(p_order->>'house_unit'), nullif(trim(p_order->>'zipcode'), ''),
    trim(p_order->>'payment_method'), nullif(trim(p_order->>'shipping_method'), ''),
    nullif(trim(p_order->>'shipping_method_type'), ''), nullif(trim(p_order->>'notes'), ''),
    greatest(coalesce((p_order->>'shipping_fee')::numeric, 0), 0),
    greatest(coalesce((p_order->>'payment_fee')::numeric, 0), 0),
    greatest(coalesce((p_order->>'subtotal')::numeric, 0), 0),
    greatest(coalesce((p_order->>'total')::numeric, 0), 0),
    greatest(coalesce((p_order->>'amount_paid')::numeric, 0), 0),
    'Pending', nullif(p_order->>'receipt_image', ''), nullif(trim(p_order->>'reference_number'), ''),
    nullif(p_order->>'paid_at', '')::timestamptz, 'Pending'
  ) returning id, orders.order_ref into v_order_id, v_order_ref;

  for v_item_json in select value from jsonb_array_elements(p_items) loop
    insert into public.order_items (
      order_id, product_id, product_name, variant_id, variant_name, variant_sku,
      unit_price, quantity, line_total
    ) values (
      v_order_id,
      nullif(v_item_json->>'product_id','')::bigint,
      coalesce(v_item_json->>'product_name',''),
      nullif(v_item_json->>'variant_id','')::bigint,
      nullif(v_item_json->>'variant_name',''),
      nullif(v_item_json->>'variant_sku',''),
      coalesce((v_item_json->>'unit_price')::numeric,0),
      greatest(coalesce((v_item_json->>'quantity')::integer,1),1),
      coalesce((v_item_json->>'line_total')::numeric,0)
    );
  end loop;
  return query select v_order_id::text, v_order_ref::text;
end;
$$;
revoke all on function public.place_storefront_order(jsonb,jsonb) from public;
grant execute on function public.place_storefront_order(jsonb,jsonb) to anon, authenticated;

