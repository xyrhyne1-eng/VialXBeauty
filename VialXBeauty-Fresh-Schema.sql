create policy payment_receipts_admin_read on storage.objects for select to authenticated using (bucket_id = 'payment-receipts' and public.is_admin());
create policy payment_receipts_admin_delete on storage.objects for delete to authenticated using (bucket_id = 'payment-receipts' and public.is_admin());

